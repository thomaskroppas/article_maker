"""
Определение интента темы статьи по правилам.
Без LLM: ищет маркеры в нижнем регистре темы.

Поддерживаются два значения:
  - "how_to"        — практическая инструкция, пошаговое действие
  - "informational" — обзор, сравнение, фактическая информация (по умолчанию)

Используется на этапе подготовки brief/outline: даёт интент для матчера
архетипов и для самой генерации, если юзер не задал интент вручную.
"""
import re
from typing import Optional


# Регэкспы маркеров. Все по нижнему регистру.
# how_to сильнее informational — если есть «как», даже при наличии «лучший»,
# побеждает how_to («как выбрать лучший X» — это инструкция).
_HOWTO_MARKERS = [
    r"\bкак\s",            # «как сделать», «как выбрать», «как починить»
    r"\bинструкци",        # «инструкция»
    r"\bпошагов",          # «пошаговый», «пошагово»
    r"\bсвоими руками\b",
    r"\bсамостоятельно\b",
    r"\bруководство\b",    # часто практическое
    r"\bнастро",           # «настроить», «настройка», «настрой»
    r"\bустанов",          # «установить», «установка»
    r"\bпочини",           # «починить»
    r"\bотремонти",        # «отремонтировать»
    r"\bоформи",           # «оформить»
    r"\bприготови",        # «приготовить»
    r"\bпосади",           # «посадить»
    r"\bухажива",          # «ухаживать»
    r"\bприучи",           # «приучить»
    r"\bсдела",            # «сделать»
    r"\bремонт\b",         # «ремонт чего-то» — практический контекст
    r"\bчто делать\b",
    r"\bкуда обратиться\b",
]

_INFORMATIONAL_MARKERS = [
    r"\bтоп[\s\-]",
    r"\bлучш",
    r"\bобзор\b",
    r"\bсравнен",
    r"\bvs\b",
    r"\bили\b",            # «X или Y»
    r"\bпротив\b",
    r"\bчто такое\b",
    r"\bвс[её] о\b",
    r"\bподборк",
    r"\bрейтинг\b",
    r"\bмиф",
    r"\bправда о\b",
]


def detect_intent(topic: Optional[str]) -> str:
    """
    Определяет интент темы.
    Если есть how_to-маркер → "how_to" (приоритет).
    Иначе если есть informational-маркер → "informational".
    Иначе fallback → "informational".
    """
    if not topic:
        return "informational"
    text = topic.lower()

    for pat in _HOWTO_MARKERS:
        if re.search(pat, text):
            return "how_to"

    for pat in _INFORMATIONAL_MARKERS:
        if re.search(pat, text):
            return "informational"

    return "informational"
